def rank_of(hits: list[dict], needle: str) -> int | None:
    """อันดับของชิ้นเอกสารที่มีข้อความที่ต้องการ (เริ่มที่ 1) หรือ None ถ้าไม่เจอ"""
    low = needle.lower()
    for i, h in enumerate(hits, start=1):
        if low in h["content"].lower() or low in h["title"].lower():
            return i
    return None


def main() -> int:
    parser = argparse.ArgumentParser(description="วัดคุณภาพการค้นเอกสารของผู้ช่วย AI")
    parser.add_argument("--show-misses", action="store_true",
                        help="แสดงชิ้นเอกสารที่ค้นได้ของข้อที่พลาด")
    args = parser.parse_args()

    conn = db_module.connect()
    k = config.AI_CONTEXT_CHUNKS
    total_chunks = conn.execute("SELECT COUNT(*) c FROM doc_chunks").fetchone()["c"]

    print(f"เอกสารในระบบ {total_chunks} ชิ้น · ส่งให้โมเดลอ่านครั้งละ {k} ชิ้น")
    print(f"คำถามที่ต้องค้นเจอ {len(CASES)} ข้อ\n")

    hit_at_1 = 0
    hit_at_k = 0
    misses: list[tuple[str, str, str, list[dict]]] = []
    by_group: dict[str, list[int]] = {}

    for group, question, needle in CASES:
        hits = retrieval.search(conn, question, limit=k)
        rank = rank_of(hits, needle)
        by_group.setdefault(group, []).append(1 if rank else 0)

        if rank == 1:
            hit_at_1 += 1
        if rank:
            hit_at_k += 1
            mark = f"อันดับ {rank}"
        else:
            mark = "ไม่เจอ"
            misses.append((group, question, needle, hits))

        status = "ผ่าน" if rank else "พลาด"
        print(f"  [{status}] {question:<42} {mark}")

    print()
    print("  " + "-" * 56)
    print(f"  recall@{k} : {hit_at_k}/{len(CASES)} ({hit_at_k / len(CASES) * 100:.0f}%)"
          "   ← ตัวเลขที่สำคัญ เพราะเป็นสิ่งที่โมเดลได้อ่านจริง")
    print(f"  recall@1 : {hit_at_1}/{len(CASES)} ({hit_at_1 / len(CASES) * 100:.0f}%)"
          "   ← อันดับหนึ่งตรงบ่อยแค่ไหน")
    print()

    print("  แยกตามหมวด")
    for group, marks in by_group.items():
        got, n = sum(marks), len(marks)
        bar = "█" * got + "·" * (n - got)
        print(f"    {group:<10} {bar}  {got}/{n}")

    # ---- คำถามนอกเรื่อง: ยิ่งค้นไม่เจอยิ่งประหยัด แต่ไม่ถือว่าผิด ----
    print("\nคำถามนอกเรื่อง (ค้นไม่เจอ = ประหยัดค่าเรียกโมเดล · ด่านปลายทางกรองอยู่แล้ว)")
    stray = 0
    for question in SHOULD_MISS:
        hits = retrieval.search(conn, question, limit=k)
        if hits:
            stray += 1
        mark = "ดี" if not hits else "เสียค่าเรียกเปล่า"
        print(f"  [{mark:<17}] {question:<42} ค้นได้ {len(hits)} ชิ้น")

    # ---- คำถามที่ต้องไม่ไปถึง AI ----
    print("\nคำถามที่มีคำตอบแน่นอน (ต้องไปฐานข้อมูล ไม่ใช่ AI)")
    leaked = 0
    for question in MUST_NOT_REACH_AI:
        guess = intent.match(conn, question)
        ok = guess.question_id is not None
        if not ok:
            leaked += 1
        print(f"  [{'ผ่าน' if ok else 'พลาด'}] {question:<42} "
              f"{guess.question_id or 'หลุดไปหา AI'}")

    if args.show_misses and misses:
        print("\nรายละเอียดข้อที่พลาด")
        for group, question, needle, hits in misses:
            print(f"\n  {question}  (มองหา '{needle}')")
            if not hits:
                print("    ค้นไม่ได้เลยสักชิ้น")
            for i, h in enumerate(hits, start=1):
                print(f"    {i}. {h['title'][:40]} · {h['content'][:70]}...")

    failed = len(misses) + leaked
    print("\n" + "=" * 60)
    if failed == 0:
        print("ผ่านทั้งหมด"
              + (f" (คำถามนอกเรื่องที่ยังค้นเจอ {stray} ข้อ — เสียค่าเรียกโมเดลเปล่า)"
                 if stray else ""))
    else:
        print(f"ต้องแก้ {failed} ข้อ "
              f"(ค้นไม่เจอ {len(misses)} · หลุดไปหา AI {leaked})"
              + (f" · คำถามนอกเรื่องที่ยังค้นเจอ {stray}" if stray else ""))
    conn.close()
    return 0 if failed == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
